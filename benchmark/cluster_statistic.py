"""
Cluster Statistic & Visualization Script.

Reads detailed cluster CSV output generated by quick_cluster.py (or grid_search scripts)
and produces comprehensive statistics & plots:
  1. Cluster Size Distribution (Histogram)
  2. Purity Distribution (Histogram)
  3. Purity vs. Cluster Size (Scatter Plot)
  4. Pure vs. Mixed Clusters Ratio (Pie Chart)

Usage:
    python benchmark/cluster_statistic.py --csv_path benchmark/results/adaface_raw_infomap_clusters_detail.csv
    python benchmark/cluster_statistic.py (automatically finds the latest _clusters_detail.csv)
"""

import sys
import argparse
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
from pathlib import Path

# Add benchmark directory to sys.path
SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
sys.path.insert(0, str(SCRIPT_DIR))


def find_latest_csv(results_dir: Path) -> Path:
    """Finds the most recently modified *_clusters_detail.csv file in results_dir."""
    csv_files = list(results_dir.glob("*_clusters_detail.csv"))
    if not csv_files:
        return None
    return max(csv_files, key=lambda f: f.stat().st_mtime)


def analyze_and_plot(csv_path: Path, output_dir: Path):
    print("=" * 80)
    print(f" CLUSTER STATISTICAL VISUALIZATION")
    print(f" Input CSV: {csv_path.name}")
    print("=" * 80)

    df = pd.read_csv(csv_path)

    # Filter out noise row if present
    df_valid = df[df["cluster_num"] != "NOISE"].copy()
    df_valid["total_images"] = pd.to_numeric(df_valid["total_images"])
    df_valid["purity"] = pd.to_numeric(df_valid["purity"])

    total_clusters = len(df_valid)
    total_images = df_valid["total_images"].sum()
    pure_clusters = (df_valid["purity"] == 1.0).sum()
    mixed_clusters = total_clusters - pure_clusters
    pure_pct = (pure_clusters / total_clusters * 100) if total_clusters > 0 else 0.0

    avg_purity = df_valid["purity"].mean() * 100
    weighted_purity = (df_valid["purity"] * df_valid["total_images"]).sum() / total_images * 100 if total_images > 0 else 0.0

    avg_size = df_valid["total_images"].mean()
    median_size = df_valid["total_images"].median()
    max_size = df_valid["total_images"].max()
    min_size = df_valid["total_images"].min()

    print("\n--- STATISTICAL SUMMARY ---")
    print(f" Total Clusters      : {total_clusters}")
    print(f" Total Images        : {total_images}")
    print(f" Cluster Size (Img)  : Mean = {avg_size:.2f} | Median = {median_size:.1f} | Min = {min_size} | Max = {max_size}")
    print(f" Pure Clusters (=100%): {pure_clusters} / {total_clusters} ({pure_pct:.2f}%)")
    print(f" Mixed Clusters      : {mixed_clusters} / {total_clusters} ({100 - pure_pct:.2f}%)")
    print(f" Average Purity      : {avg_purity:.2f}%")
    print(f" Weighted Purity     : {weighted_purity:.2f}% (weighted by cluster size)")
    print("-" * 80)

    # Set matplotlib style
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    fig, axes = plt.subplots(2, 2, figsize=(14, 10))
    fig.suptitle(f"Cluster Analysis Statistics: {csv_path.stem}", fontsize=16, fontweight="bold")

    # 1. Cluster Size Distribution (Histogram)
    ax1 = axes[0, 0]
    ax1.hist(df_valid["total_images"], bins=30, color="#3498db", edgecolor="black", alpha=0.8)
    ax1.axvline(avg_size, color="red", linestyle="--", linewidth=1.5, label=f"Mean: {avg_size:.1f}")
    ax1.axvline(median_size, color="green", linestyle="-.", linewidth=1.5, label=f"Median: {median_size:.1f}")
    ax1.set_title("1. Cluster Size Distribution", fontsize=12, fontweight="bold")
    ax1.set_xlabel("Number of Images per Cluster")
    ax1.set_ylabel("Frequency (Cluster Count)")
    ax1.legend()

    # 2. Purity Distribution (Histogram)
    ax2 = axes[0, 1]
    ax2.hist(df_valid["purity"] * 100, bins=20, color="#2ecc71", edgecolor="black", alpha=0.8)
    ax2.axvline(avg_purity, color="red", linestyle="--", linewidth=1.5, label=f"Mean Purity: {avg_purity:.1f}%")
    ax2.set_title("2. Cluster Purity Distribution (%)", fontsize=12, fontweight="bold")
    ax2.set_xlabel("Purity Score (%)")
    ax2.set_ylabel("Frequency (Cluster Count)")
    ax2.legend()

    # 3. Purity vs. Cluster Size (Scatter Plot)
    ax3 = axes[1, 0]
    scatter = ax3.scatter(
        df_valid["total_images"],
        df_valid["purity"] * 100,
        c=df_valid["purity"],
        cmap="viridis",
        alpha=0.6,
        edgecolors="none",
        s=40
    )
    ax3.set_title("3. Purity vs. Cluster Size", fontsize=12, fontweight="bold")
    ax3.set_xlabel("Cluster Size (Total Images)")
    ax3.set_ylabel("Purity (%)")
    fig.colorbar(scatter, ax=ax3, label="Purity Ratio")

    # 4. Pure vs. Mixed Clusters Breakdown (Pie Chart)
    ax4 = axes[1, 1]
    labels = [f"Pure Clusters (100%)\n({pure_clusters})", f"Mixed Clusters (<100%)\n({mixed_clusters})"]
    sizes = [pure_clusters, mixed_clusters]
    colors = ["#2ecc71", "#e74c3c"]
    ax4.pie(sizes, labels=labels, colors=colors, autopct="%1.1f%%", startangle=140, explode=(0.05, 0), wedgeprops={"edgecolor": "black"})
    ax4.set_title(f"4. Pure vs. Mixed Ratio (Total: {total_clusters} Clusters)", fontsize=12, fontweight="bold")

    plt.tight_layout(rect=[0, 0, 1, 0.95])

    # Save output plot
    out_dir = PROJECT_ROOT / output_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    plot_file = out_dir / f"{csv_path.stem}_plot.png"
    plt.savefig(plot_file, dpi=300)
    plt.close()

    print(f"\n[ALERT] Visualization plot saved successfully:")
    print(f"        --> {plot_file}")


def main():
    parser = argparse.ArgumentParser(description="Cluster Statistic & Visualization Script")
    parser.add_argument("--csv_path", type=str, default=None, help="Path to detailed cluster CSV file")
    parser.add_argument("--output_dir", type=str, default="benchmark/results/plots", help="Directory to save output plots")
    args = parser.parse_args()

    results_dir = PROJECT_ROOT / "benchmark" / "results"

    if args.csv_path:
        csv_file = Path(args.csv_path)
        if not csv_file.is_absolute():
            csv_file = PROJECT_ROOT / csv_file
    else:
        csv_file = find_latest_csv(results_dir)
        if not csv_file:
            print("Error: No '*_clusters_detail.csv' file found in 'benchmark/results/'.")
            print("Please run quick_cluster.py first, or specify --csv_path.")
            sys.exit(1)

    if not csv_file.exists():
        print(f"Error: Specified CSV file does not exist: {csv_file}")
        sys.exit(1)

    analyze_and_plot(csv_file, args.output_dir)


if __name__ == "__main__":
    main()
